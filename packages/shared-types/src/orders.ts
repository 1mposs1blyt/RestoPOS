import type {
  ISODateString,
  Money,
  OrderItemStatus,
  OrderStatus,
  PaymentKind,
  TableStatus,
  UUID,
} from "./common";

export interface Table {
  id: UUID;
  venueId: UUID;
  label: string;
  status: TableStatus;
}

export interface Order {
  id: UUID;
  venueId: UUID;
  /** `null` — заказ без стола: навынос или с прилавка. */
  tableId: UUID | null;
  shiftId: UUID;
  waiterId: UUID;
  status: OrderStatus;
  /**
   * Порядковый номер заказа в смене. На прилавке его называют гостю и печатают
   * в чеке — без него выданную еду не с чем сопоставить, ведь стола нет.
   */
  number: number;
  /**
   * Сколько гостей за столом. Нужно и для деления счёта, и для отчётов:
   * средний чек на гостя — не то же самое, что средний чек на заказ.
   * Отсутствует у старых заказов и на прилавке, где гость всегда один.
   */
  guestCount?: number;
  createdAt: ISODateString;
  /**
   * Номер кассовой смены, в которую заказ закрыт, и номер чека в ней.
   * Проставляются при оплате и дальше неизменны: по этой паре закрытый чек
   * ищут в реестре счетов и сверяют с Z-отчётом.
   */
  cashShiftNumber?: number;
  receiptNumber?: number;
  /**
   * Номер заказа во внешней системе — агрегатор доставки, сайт, приложение.
   * Свой `number` для них бесполезен: гость называет номер из своего приложения.
   */
  externalNumber?: string;
  /**
   * Временный идентификатор, присвоенный терминалом в офлайне.
   * Сервер использует его для идемпотентной привязки при синхронизации,
   * чтобы повторная отправка очереди не создала дубль заказа.
   */
  clientId?: string;
}

export interface OrderItem {
  id: UUID;
  orderId: UUID;
  menuItemId: UUID;
  /**
   * Количество. Дробное после деления блюда: «1 = 2 × 0,5» даёт две позиции
   * по 0,5 (см. `lib/split-quantity.ts`).
   */
  quantity: number;
  status: OrderItemStatus;
  /** Идентификаторы применённых модификаторов (`order_item_modifiers`). */
  modifierIds: UUID[];
  /**
   * Доля какой позиции. `null`/отсутствует — самостоятельная позиция.
   * Ссылка нужна, чтобы в чеке было видно, из чего доля получилась:
   * «полборща» без исходного борща выглядит опечаткой.
   */
  splitOf?: UUID | null;
  /**
   * Чей это заказ внутри компании. Номер, а не ссылка на гостя: гости стола
   * безымянны, их различают «первый», «второй» — и этого достаточно, чтобы
   * разбить счёт. `null`/отсутствует — общая позиция.
   */
  guestNumber?: number | null;
}

/**
 * Тип оплаты — справочник заведения.
 *
 * Их не два и не фиксированное число: «Наличные», «Банковские карты»,
 * «Безнал. расчёт», «Без выручки», а у сети — ещё и свои. Перечислением
 * это не описать, иначе каждый новый тип означает пересборку кассы.
 */
export interface PaymentType {
  id: UUID;
  venueId: UUID;
  label: string;
  kind: PaymentKind;
  /**
   * Идёт ли в выручку. У «без выручки» — нет: чек есть, блюда списываются,
   * денег не приходит.
   */
  countsAsRevenue: boolean;
  /** Открывать ли денежный ящик при оплате этим типом. */
  opensDrawer: boolean;
  /** Порядок на экране оплаты. Наличные первыми — ими платят чаще всего. */
  sortOrder: number;
}

/**
 * Строка оплаты заказа.
 *
 * Оплата — **список**, а не одно поле: гость платит часть картой, часть
 * наличными, и каждая часть это отдельный факт с своей суммой. Одно поле
 * `method` заставляло бы выбирать, какой из двух платежей «настоящий».
 *
 * Append-only и иммутабельно (инвариант №6): LWW на платеже означает
 * потерянную выручку. Возврат — это **новая** строка с `refundOf`, а не
 * правка или удаление исходной.
 *
 * `label` и `kind` продублированы из справочника намеренно. Закрытый чек —
 * финансовый документ: если менеджер через год переименует тип оплаты или
 * удалит его, Z-отчёт за прошлый год обязан остаться читаемым.
 */
export interface Payment {
  id: UUID;
  orderId: UUID;
  /** Смена, в которую попал платёж. По ней сводится X- и Z-отчёт. */
  cashShiftId: UUID;
  paymentTypeId: UUID;
  /** Снимок рода на момент оплаты. */
  kind: PaymentKind;
  /** Снимок названия на момент оплаты. */
  label: string;
  amount: Money;
  tipAmount: Money;
  /**
   * Сколько наличных дал гость. Нужно только для сдачи и только для наличных:
   * у карты «принято» всегда равно сумме. `null` — неприменимо.
   */
  tendered: Money | null;
  /** Кто провёл оплату. */
  staffId: UUID;
  /** Для возврата — ссылка на возвращаемый платёж. */
  refundOf: UUID | null;
  paidAt: ISODateString;
  clientId?: string;
}
