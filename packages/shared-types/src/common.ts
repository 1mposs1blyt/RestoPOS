/** UUID v4 в строковом виде — первичные ключи всех сущностей. */
export type UUID = string;

/** Метка времени ISO-8601 (`TIMESTAMPTZ` на стороне PostgreSQL). */
export type ISODateString = string;

/**
 * Денежная сумма. На бэкенде это `NUMERIC(10,2)`, который драйвер отдаёт строкой,
 * чтобы не терять точность в float. Держим строкой и на клиенте: арифметику
 * делаем только там, где явно приводим к минорным единицам (копейкам).
 */
export type Money = string;

export type PlanCode = "start" | "standard" | "pro";

/**
 * Булевы модули, привязанные к тарифу (таблица `plan_features`).
 * Числовые ограничения (`maxTerminals`, `maxVenues`) — это quota на Plan,
 * а не feature-flag, и проверяются отдельным механизмом.
 */
export type FeatureCode =
  | "warehouse"
  | "kds"
  | "delivery"
  | "reports"
  | "egais"
  | "loyalty"
  | "analytics"
  | "suppliers"
  | "multi_venue";

export type SubscriptionStatus = "active" | "past_due" | "canceled";

export type TerminalKind = "pos" | "kds" | "admin";

/**
 * Роли персонала плюс вендорская `support`.
 *
 * `support` — тех. специалист с нашей стороны, а не сотрудник арендатора:
 * ему доступен только сервисный экран терминала. На бэкенде такой вход
 * правильно держать вне `staff` организации (см. `docs/access.md`), чтобы
 * он не попадал в квоту `max_staff` и не был виден менеджеру в списке персонала.
 */
export type StaffRole =
  | "waiter"
  | "cashier"
  | "manager"
  | "cook"
  | "support";

/**
 * Как заведение обслуживает гостей.
 *
 * `tables` — зал со схемой столов: заказ открывается на стол и живёт, пока
 * гость сидит. `counter` — прилавок (шаурмечная, кофейня навынос): столов нет,
 * заказ набирают и сразу рассчитывают, а гостя зовут по номеру.
 */
export type ServiceMode = "tables" | "counter";

export type TableStatus = "free" | "occupied" | "reserved";

export type OrderStatus = "open" | "sent_to_kitchen" | "paid" | "canceled";

/**
 * Статус позиции заказа.
 *
 * `voided` — сторно: позиция уже уехала на кухню, и удалить её нельзя
 * (append-only на `order_items`, инвариант №6) — потерянная позиция означает
 * либо несъеденное блюдо, либо неоплаченное. Поэтому она остаётся в заказе
 * помеченной: из суммы выпадает, с кухни уходит, в истории заказа видна.
 */
export type OrderItemStatus =
  | "new"
  | "cooking"
  | "ready"
  | "served"
  | "voided"
  /**
   * Разделена на доли. Позиция остаётся в чеке как история (append-only,
   * инвариант №6 — удалять её нельзя, блюдо-то приготовлено), но из суммы
   * выпадает: деньги теперь несут её доли, и считать оба уровня значит
   * взять с гостя дважды.
   *
   * От `voided` отличается смыслом и потому не сводится к нему: сторно —
   * это «блюда не будет», деление — «блюдо есть, платят за него несколько».
   */
  | "split";

/**
 * Род типа оплаты. Не сам тип: типов в заведении может быть сколько угодно
 * («Сбербанк», «Долями», «Питание персонала»), а обрабатываются они одним
 * из четырёх способов.
 *
 * `no_revenue` — не скидка 100%, а отдельный род: питание персонала,
 * представительские, списание. В выручку не идёт, но чек существует и блюда
 * из склада списываются. Свести его к скидке — значит потерять эту разницу
 * в отчётах (у iiko под это есть отдельный отчёт «032 Питание персонала»).
 */
export type PaymentKind = "cash" | "card" | "external" | "no_revenue";

/*
 * Куда позиция уезжает на приготовление, раньше было перечислением
 * `"kitchen" | "bar"`. Стало справочником на заведение (`kitchen.ts`):
 * у ресторана бывают холодный и горячий цеха, пицца, суши — двумя
 * значениями это не описать, а менять перечисление под каждого клиента
 * означает пересборку ради данных.
 */

export type MeasurementUnit = "kg" | "l" | "pcs";
