import type { ISODateString, Money, UUID } from "./common";

/**
 * Скидки и надбавки.
 *
 * Надбавка — **отдельный род, а не отрицательная скидка**. Сведя их в одно
 * знаковое поле, мы потеряли бы отчёт: скидка это потеря выручки, надбавка
 * (обслуживание, доставка) — её источник, и в сумме они могут дать ноль.
 * Без разделения это выглядит как «ничего не было».
 */
export type DiscountKind = "discount" | "surcharge";

/** Процент от подытога либо фиксированная сумма. */
export type DiscountMode = "percent" | "amount";

/**
 * Справочник скидок заведения: «Гостевая 10%», «Персонал 30%», «Обслуживание 10%».
 *
 * Справочник, а не свободный ввод, по той же причине, что и типы оплаты:
 * произвольная скидка от руки не даёт свести отчёт «кто и за что скидывал»,
 * а именно ради него всё и делается. Ручная скидка остаётся возможной,
 * но это отдельное право с подтверждением.
 */
export interface DiscountType {
  id: UUID;
  venueId: UUID;
  label: string;
  kind: DiscountKind;
  mode: DiscountMode;
  /** Проценты (10 = 10%) либо сумма — по `mode`. */
  value: string;
  /**
   * Требует подтверждения чужим PIN. Право `order.discount` побиваемое,
   * и большие скидки логично закрывать подтверждением менеджера, а мелкие
   * гостевые — нет.
   */
  requiresApproval: boolean;
  isActive: boolean;
  sortOrder: number;
}

/**
 * Применённая к заказу скидка.
 *
 * `label`, `mode` и `value` продублированы из справочника снимком — по той же
 * причине, что и у платежа: закрытый чек это финансовый документ, и правка
 * справочника через год не должна менять прошлогодний отчёт.
 *
 * `amount` — рассчитанная сумма, тоже снимком: пересчитывать процент при
 * каждом показе значит получить другое число, если состав чека изменился
 * после применения.
 */
export interface OrderDiscount {
  id: UUID;
  orderId: UUID;
  /** `null` — скидка введена вручную, минуя справочник. */
  discountTypeId: UUID | null;
  kind: DiscountKind;
  mode: DiscountMode;
  label: string;
  value: string;
  amount: Money;
  /** Позиция, если скидка на одно блюдо. `null` — на весь заказ. */
  orderItemId: UUID | null;
  staffId: UUID;
  /** Кто подтвердил, если скидка требовала подтверждения. */
  approvedBy: UUID | null;
  appliedAt: ISODateString;
  clientId?: string;
}
