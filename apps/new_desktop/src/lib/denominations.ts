/**
 * Номиналы наличных, которые ходят по рукам.
 *
 * Монеты здесь обязательны: гость доплачивает десятками и полтинниками,
 * чтобы получить сдачу покрупнее, и «1000» в качестве единственного способа
 * внести деньги заставляет кассира считать в уме то, что должна считать касса.
 */
export const DENOMINATIONS = [1, 2, 5, 10, 50, 100, 200, 500, 1000, 2000, 5000];

const RUBLES = new Intl.NumberFormat("ru-RU");

/** Подпись номинала без знака рубля: на узкой кнопке он только мешает. */
export function formatDenomination(rubles: number): string {
  return RUBLES.format(rubles);
}
