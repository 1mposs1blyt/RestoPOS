import { describe, expect, it } from "vitest";
import type { MenuItem, OrderItem } from "@restopos/shared-types";
import { lineTotal, unitPrice } from "./order-price";

/**
 * Снимок цены в позиции — это про деньги гостя, а не про аккуратность.
 *
 * Меню правят в течение смены: блюдо дорожает, блюдо снимают с продажи.
 * Пока цена бралась из меню при каждом пересчёте, уже собранный чек менялся
 * задним числом, а у снятого блюда строка обнулялась — и гость недоплачивал.
 */

const ЭСПРЕССО = "77777777-7777-7777-7777-777777777771";

function позиция(patch: Partial<OrderItem> = {}): OrderItem {
  return {
    id: "item-1",
    orderId: "order-1",
    menuItemId: ЭСПРЕССО,
    quantity: 1,
    status: "new",
    modifierIds: [],
    ...patch,
  };
}

/** Меню, в котором эспрессо стоит `price`. Пустое — блюда в меню нет. */
function меню(price: string | null) {
  const item = {
    id: ЭСПРЕССО,
    categoryId: "cat-1",
    name: "Эспрессо",
    price,
  } as unknown as MenuItem;

  return (id: string) => (price !== null && id === ЭСПРЕССО ? item : undefined);
}

describe("цена позиции заказа", () => {
  it("берётся из позиции, а не из меню", () => {
    // Блюдо подорожало после того, как его набрали в чек.
    const item = позиция({ price: "180.00" });
    expect(unitPrice(item, меню("250.00"))).toBe("180.00");
  });

  it("сохраняется, даже если блюдо убрали из меню", () => {
    /*
     * Тот самый случай, ради которого поле и заведено: без снимка строка
     * обнулялась и гость платил меньше, чем заказал.
     */
    const item = позиция({ price: "180.00", quantity: 2 });
    expect(unitPrice(item, меню(null))).toBe("180.00");
    expect(lineTotal(item, меню(null))).toBe("360.00");
  });

  it("у заказов из прошлой версии берётся из меню", () => {
    // Поля `price` там нет вовсе — обнулять такие строки нельзя, за ними
    // сидят гости с открытыми чеками.
    const item = позиция();
    expect(unitPrice(item, меню("250.00"))).toBe("250.00");
  });

  it("у старой позиции без блюда в меню — ноль, а не выдумка", () => {
    // Кассир увидит пустую строку и разберётся; подставленная цена
    // разошлась бы с тем, что гостю называли.
    const item = позиция();
    expect(unitPrice(item, меню(null))).toBe("0.00");
  });

  it("стоимость строки — цена на количество", () => {
    const item = позиция({ price: "180.00", quantity: 3 });
    expect(lineTotal(item, меню("250.00"))).toBe("540.00");
  });

  it("дробное количество после деления блюда считается от снимка", () => {
    // Доли наследуют цену исходной позиции (редьюсер копирует её целиком).
    const item = позиция({ price: "420.00", quantity: 0.5 });
    expect(lineTotal(item, меню(null))).toBe("210.00");
  });
});
